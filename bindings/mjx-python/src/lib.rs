//! `mjx_ooxml` for Python — the whole PowerPoint surface, as an extension module.
//!
//! ```python
//! import mjx_ooxml
//!
//! deck = mjx_ooxml.Deck.open(open("in.pptx", "rb").read())
//! for index in range(deck.slide_count()):
//!     print(index, deck.shape_text(index, 0))
//! ```
//!
//! # What this crate is
//!
//! A thin, complete projection of [`mjx_ooxml`] — 257 `Deck` methods and the 205 classes their
//! arguments and results are made of. It adds no behaviour: every method calls exactly one method
//! one layer down, and every class wraps exactly one value. What it *does* add is the shape a
//! Python caller expects — an exception hierarchy, keyword arguments, `bytes`, `list`, `dict`, and
//! a bare `int` where Rust would take an `impl Into<Surface>`.
//!
//! ## The mapping is identity
//!
//! `mjx-ooxml`'s method and field names are already `snake_case` and already self-explanatory, so
//! nothing is renamed: `deck.set_shape_run_properties(…)` in Rust is
//! `deck.set_shape_run_properties(…)` in Python, and the guide translates line for line. There are
//! exactly two exceptions, both forced:
//!
//! * `None` is a Python keyword, so the `None` **member** of nine enumerations is spelled `NONE`.
//!   See [`enums`].
//! * `Deck.presentation`, `Deck.presentation_mut` and `Deck.into_presentation` are absent, because
//!   all three hand back a `Presentation` — the Rust-only escape hatch whose value is precisely the
//!   `ShapeCursor` and closure-taking readers a binding cannot carry.
//!
//! The WebAssembly binding diverges on purpose: it is `camelCase`, because a `snake_case` API is an
//! immediate smell to a TypeScript consumer, while Python's own standard library is `snake_case`.
//!
//! # Safety
//!
//! This crate carries `#![allow(unsafe_code)]`, against a workspace that denies it. The
//! justification, in full:
//!
//! **There is no hand-written `unsafe` in this crate.** Every `unsafe` block reaching the compiler
//! is generated by `#[pyclass]`, `#[pymethods]`, `#[pyfunction]` or `#[pymodule]` — the macros that
//! own the CPython ABI contract, implement `PyTypeInfo` and `PyClassImpl`, and lay out the type
//! objects CPython requires. The allowance exists because those expansions land in this crate's
//! token stream, not because this crate performs unsafe operations of its own. This is the first
//! use of the `deny`-not-`forbid` escape hatch the workspace lints were written to permit
//! (`Cargo.toml`'s `[workspace.lints.rust]`), and CI enforces the claim: `.github/workflows/ci.yml`
//! greps `bindings/*/src` for `unsafe` outside this comment and fails if it finds any.
//!
//! # Panics
//!
//! A panic crossing the CPython boundary is not a Python exception; PyO3 catches the unwind and
//! turns it into `pyo3_runtime.PanicException`, which is why the workspace release profile keeps
//! `panic = "unwind"`. But that is a backstop, not a design: **every fallible path in this crate
//! returns a `PyErr`.** No `unwrap`, no `expect`, no indexing that can go out of range — the
//! conversions in [`errors`] are written so that even a failure while *building* an exception
//! yields an exception.

// See the module documentation above: no hand-written `unsafe` appears in this crate; the
// allowance covers only the blocks the PyO3 attribute macros generate.
#![allow(unsafe_code)]

use pyo3::prelude::*;
use pyo3::types::PyModule;

#[macro_use]
mod support;

// Every module is public so the crate is usable as an ordinary Rust library too — `cargo test`
// builds it as an `rlib` — and so that `unreachable_pub` has nothing to complain about: a
// `#[pyclass]` must be nameable from wherever PyO3's generated code refers to it.
