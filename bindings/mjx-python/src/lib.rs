/// The `mjx_ooxml` extension module.
///
/// Registration order matters only for the exceptions, which are created on first use and must
/// exist before any method can raise one; everything else is independent.
#[pymodule]
fn _mjx_ooxml(module: &Bound<'_, PyModule>) -> PyResult<()> {
    module.add("__doc__", MODULE_DOC)?;
    module.add("__version__", env!("CARGO_PKG_VERSION"))?;

    errors::register(module)?;
    enums::register(module)?;
    address::register(module)?;
    measures::register(module)?;
    paint::register(module)?;
    text::register(module)?;
    geometry::register(module)?;
    three_d::register(module)?;
    tables::register(module)?;
    charts::register(module)?;
    content::register(module)?;
    format::register(module)?;
    deck::register(module)?;

    // `__all__` is derived from what was actually registered, so it cannot drift from the module:
    // a class added above appears here, and one removed disappears. `from mjx_ooxml import *`
    // therefore imports exactly the documented surface and nothing else.
    let mut exported: Vec<String> = module
        .dict()
        .keys()
        .iter()
        .filter_map(|name| name.extract::<String>().ok())
        .filter(|name| !name.starts_with("__"))
        .collect();
    exported.sort();
    module.add("__all__", exported)
}

/// What `help(mjx_ooxml)` shows.
const MODULE_DOC: &str = "\
Read, edit and write PowerPoint files — a pure-Rust OOXML library, bound to Python.

    import mjx_ooxml

    deck = mjx_ooxml.Deck.blank(mjx_ooxml.SlideSize.widescreen())
    slide = deck.add_slide_from_layout(0)
    deck.add_text_box(slide, 'Hello', mjx_ooxml.ShapeBounds.from_inches(1, 1, 6, 1))
    open('out.pptx', 'wb').write(deck.save())

The library is bytes in and bytes out: it never touches a filesystem, a clock, a thread or a
random number generator, so the file I/O above is deliberately the caller's.

Addressing. A surface is an int (the slide index) or a Surface; a shape is an int (a top-level
shape), a list of ints (a descent through groups), or a ShapePath. Both spellings work wherever
either is expected.

Errors. Everything raises a subclass of OoxmlError, one per error code, each carrying .code and
the coordinates .surface, .shape, .row, .column and .index. IndexOutOfRangeError is also an
IndexError.

Threading. Use one Deck from one thread. Deck.open and Deck.save release the interpreter lock;
nothing else does enough work to be worth it.
";
