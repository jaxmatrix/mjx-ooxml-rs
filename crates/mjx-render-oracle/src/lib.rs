/// Compare one specimen against its committed baseline, at all three tiers.
///
/// `perturbation` is what was deliberately changed before rendering; a check run passes
/// [`Perturbation::None`] and the two gate tests pass the others.
///
/// # Errors
///
/// A sentence, when the baseline cannot be used at all — no approval, a stale digest, a missing
/// artefact — or when the specimen will not render. **An unusable baseline is an error and never a
/// tier outcome**, because a comparison against a baseline nobody approved is the tautology this
/// crate exists to refuse, and reporting it as *"the tiers agreed"* would be that tautology with a
/// green tick on it.
pub fn compare_against_baseline(
    baselines: &Baselines,
    specimen: &Specimen,
    perturbation: Perturbation,
) -> Result<LayeredComparison, String> {
    let approval = baselines.approval(specimen.name);
    if let Some(refusal) = approval.refusal() {
        return Err(format!("`{}`: {refusal}", specimen.name));
    }

    let tree = specimen::fragments(specimen, perturbation);
    let taken_fragments = snapshot::fragments(&tree);
    let stored_fragments = snapshot::Snapshot::parse(&String::from_utf8_lossy(
        &baselines.artefact(specimen.name, baseline::ARTEFACTS[0])?,
    ));

    let list = specimen::display_list(specimen, perturbation)?;
    let taken_commands = snapshot::commands(&list);
    let stored_commands = snapshot::Snapshot::parse(&String::from_utf8_lossy(
        &baselines.artefact(specimen.name, baseline::ARTEFACTS[1])?,
    ));

    let rendered = specimen::render(specimen, perturbation)?;
    let taken_image = png::image_from_pixels(&rendered.pixels);
    let stored_image = png::decode(&baselines.artefact(specimen.name, baseline::ARTEFACTS[2])?)?;
    // **Not a byte compare**, even though these two would be byte-identical on a run that changed
    // nothing. The metric is what makes a failure say *where* the page moved and how much, and it
    // is the same metric the cross-producer pixel tier in `crate::pdf` uses — one instrument, held
    // to two tolerances, rather than a strict path here and a lenient one there that could disagree
    // about what "the same picture" means.
    let difference = perceptual::compare(&taken_image, &stored_image, specimen.tolerance)?;
    let pixels = TierOutcome::from_difference(&difference, specimen.tolerance);

    Ok(LayeredComparison {
        specimen: specimen.name.to_owned(),
        // The tiers compare against this crate's own committed baselines, which no external producer
        // made. `None` is a *provider that answers nothing*, not the absence of one — which is what
        // keeps `may_be_called_parity` false rather than unasked.
        provider: ReferenceProvider::None,
        content: specimen.content,
        fragments: TierOutcome::from_snapshots(&taken_fragments, &stored_fragments),
        commands: TierOutcome::from_snapshots(&taken_commands, &stored_commands),
        pixels,
    })
}
