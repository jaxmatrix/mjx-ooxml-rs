//! **Tier one, over the Excel corpus.** One committed text snapshot per band, compared line by line,
//! so a position regression surfaces as *"line 14: node 6's rect is 152400 wide and was 101600"*
//! rather than as a mysterious picture.
//!
//! # Why this is here and not in `mjx-render-oracle`
//!
//! MJXOFF-165 built exactly this machinery — the three assertion tiers, the localisation, the
//! approval records — and R16's ticket asks for it to be used. **It cannot be, and the reason is
//! structural rather than a preference.** `mjx-render-oracle` depends on `mjx-paint`, which links
//! Vulkan; `xtask/tests/layering.rs` therefore forbids *any* ranked crate from naming it, in either
//! dependency section, because a test build that links Vulkan is still a build that links Vulkan.
//! This crate has a rank, so the edge is refused by name.
//!
//! The oracle cannot host these snapshots either: it is specified to name no format crate at all —
//! it is the rendering path with no document anywhere in it — and a specimen read from a `.xlsx`
//! would make every one of its baselines a baseline of the box model as well as of the renderer,
//! which is exactly the confusion it was built to prevent.
//!
//! So the *technique* is copied and the crate is not, exactly as `mjx-layout-pptx` does: the same
//! line shape, down to carrying a glyph **count** rather than glyph ids, because a baseline holding
//! glyph ids is a baseline of a shaper version and a patch release of `swash` would expire it for a
//! reason that has nothing to do with layout.
//!
//! # ⚠ Regeneration is deliberately not automatic
//!
//! A golden file generated by the code under test always matches the code under test. So
//! regeneration refuses without `MJX_LAYOUT_XLSX_REGENERATE=1`, and every committed baseline states
//! who approved it. Today every one says `generator`, which is a real record — it says the file is a
//! **change detector** and that no person has looked at it — and is not a human review. The Windows
//! sitting is where a person approves what these numbers should be.

mod support;

use std::path::{Path, PathBuf};

use support::{model, snapshot, viewport};

/// One band of one sheet, with a committed baseline.
struct Specimen {
    /// The fixture it is read from.
    file: &'static str,
    /// Which tab.
    sheet: usize,
    /// Which band of it.
    band: u32,
    /// Why this one is in the corpus — the thing its snapshot would notice.
    covers: &'static str,
}

