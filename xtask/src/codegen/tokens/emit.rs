/// Renders `ui/tokens/tokens.css`.
///
/// Two layers. The first declares every token in the source as a flat custom property under the
/// name the source stylesheet itself uses (`--color-paper`, `--radius-card`), which is what makes
/// *"drop the platform into a host that already defines these properties and it re-themes with no
/// code change"* true rather than aspirational. The second resolves each scheme group onto a
/// scheme-independent name (`--theme-background`), in the only cascade order that behaves: light by
/// default, dark when the system asks for it and the host has not said otherwise, dark whenever the
/// host says so explicitly.
pub(crate) fn css(set: &TokenSet) -> String {
    let mut out = String::new();
    out.push_str("/*\n");
    let _ = writeln!(out, " * {GENERATED_BY}");
    out.push_str(" * DO NOT EDIT. Edit the source and regenerate.\n *\n");
    for line in wrap(&set.description, COMMENT_WIDTH) {
        let _ = writeln!(out, " * {line}");
    }
    out.push_str(" */\n\n:root {\n");
    css_entries(&set.entries, &mut out);
    out.push_str("}\n");

    let aliases = scheme_aliases(set);
    if !aliases.is_empty() {
        css_scheme_layer(set, &aliases, &mut out);
    }
    out
}

fn css_entries(entries: &[Entry], out: &mut String) {
    for entry in entries {
        match entry {
            Entry::Group(group) => {
                let _ = writeln!(out, "\n  /* ── {} ──", dotted(&group.path));
                if let Some(description) = &group.description {
                    for line in wrap(description, COMMENT_WIDTH - 5) {
                        let _ = writeln!(out, "     {line}");
                    }
                }
                out.push_str("  */\n");
                css_entries(&group.entries, out);
            }
            Entry::Token(token) => {
                if let Some(description) = &token.description {
                    for line in wrap(description, COMMENT_WIDTH - 5) {
                        let _ = writeln!(out, "  /* {line} */");
                    }
                }
                if let Some(note) = provenance(token) {
                    let _ = writeln!(out, "  /* {note} */");
                }
                let _ = writeln!(
                    out,
                    "  {}: {};",
                    custom_property(&token.path),
                    token.value.css()
                );
            }
        }
    }
}

fn css_scheme_layer(set: &TokenSet, aliases: &[SchemeAlias], out: &mut String) {
    let default_scheme = 0;
    out.push_str("\n/*\n * The colour-scheme layer. Every property below resolves to whichever\n");
    out.push_str(" * scheme is in force, so a component names `--theme-surface` and never a\n");
    out.push_str(" * scheme. The order of the three rules is the behaviour: the light scheme is\n");
    out.push_str(" * the default, the system's preference wins unless the host has asked for\n");
    out.push_str(" * light, and an explicit `data-theme` wins over both.\n */\n");

    let _ = writeln!(out, "\n:root {{");
    for alias in aliases {
        let _ = writeln!(
            out,
            "  {}: var({});",
            alias.custom_property, alias.per_scheme[default_scheme]
        );
    }
    out.push_str("}\n");

    for (at, scheme) in set.scheme_names.iter().enumerate().skip(1) {
        let _ = writeln!(
            out,
            "\n@media (prefers-color-scheme: {scheme}) {{\n  :root:not([data-theme=\"{}\"]) {{",
            set.scheme_names[default_scheme]
        );
        for alias in aliases {
            let _ = writeln!(
                out,
                "    {}: var({});",
                alias.custom_property, alias.per_scheme[at]
            );
        }
        out.push_str("  }\n}\n");
    }

    for (at, scheme) in set.scheme_names.iter().enumerate() {
        if at == default_scheme {
            continue;
        }
        let _ = writeln!(out, "\n:root[data-theme=\"{scheme}\"] {{");
        for alias in aliases {
            let _ = writeln!(
                out,
                "  {}: var({});",
                alias.custom_property, alias.per_scheme[at]
            );
        }
        out.push_str("}\n");
    }
}

