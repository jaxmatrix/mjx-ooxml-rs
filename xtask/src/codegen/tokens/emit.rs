/// Renders `ui/tokens/tokens.ts`: one interface per group, the `Tokens` type, the constant that
/// satisfies it, and the map from a token's path to the CSS custom property a host would override
/// it with — which is the half of the runtime resolver's contract this child owns.
///
/// Property names are **camelCase**, from the same rule `bindings/mjx-wasm` applies to every method
/// it exports: a `snake_case` API is an immediate smell to a TypeScript consumer.
pub(crate) fn typescript(set: &TokenSet) -> String {
    let mut out = String::new();
    out.push_str("/**\n");
    let _ = writeln!(out, " * {GENERATED_BY}");
    out.push_str(" * DO NOT EDIT. Edit the source and regenerate.\n *\n");
    for line in wrap(&set.description, COMMENT_WIDTH) {
        let _ = writeln!(out, " * {line}");
    }
    out.push_str(" */\n");

    let mut emitted: BTreeSet<&str> = BTreeSet::new();
    for group in set.groups() {
        if !emitted.insert(group.rust_type.as_str()) {
            continue;
        }
        typescript_interface(group, &mut out);
    }

    out.push_str("\n/** The whole token set. */\nexport interface Tokens {\n");
    typescript_members(&set.entries, &mut out);
    out.push_str("}\n");

    if !set.scheme_names.is_empty() {
        out.push_str("\n/** The colour schemes every scheme group in the source declares. */\n");
        let _ = writeln!(
            out,
            "export type ColorScheme = {};",
            set.scheme_names
                .iter()
                .map(|scheme| format!("'{scheme}'"))
                .collect::<Vec<_>>()
                .join(" | ")
        );
    }

    out.push_str("\n/** The generated defaults — the values this platform ships with. */\n");
    out.push_str("export const tokens: Tokens = {\n");
    typescript_values(&set.entries, 1, &mut out);
    out.push_str("};\n");

    out.push_str(
        "
/**
 * Every token's CSS custom property, keyed by its path in `tokens`. A runtime resolver reads these
 * names off the host element; a host that already defines one is re-theming the platform, which is
 * exactly what it is meant to be able to do.
 */
export const customProperties: Readonly<Record<string, string>> = {
",
    );
    for token in set.tokens() {
        let _ = writeln!(
            out,
            "  '{}': '{}',",
            typescript_path(&token.path),
            custom_property(&token.path)
        );
    }
    out.push_str("};\n");
    out
}

fn typescript_interface(group: &Group, out: &mut String) {
    out.push('\n');
    typescript_doc(group.description.as_deref(), None, 0, out);
    let _ = writeln!(out, "export interface {} {{", group.rust_type);
    typescript_members(&group.entries, out);
    out.push_str("}\n");
}

fn typescript_members(entries: &[Entry], out: &mut String) {
    for entry in entries {
        match entry {
            Entry::Group(group) => {
                typescript_doc(group.description.as_deref(), None, 1, out);
                let _ = writeln!(
                    out,
                    "  readonly {}: {};",
                    typescript_property(group.path.last().map_or("", String::as_str)),
                    group.rust_type
                );
            }
            Entry::Token(token) => {
                // TypeScript erases the token's own type — a dimension and a colour are both
                // `string` — so the note carries it. Rust's field type says it already.
                let note = format!(
                    "CSS: `{}` · type `{}`{}",
                    custom_property(&token.path),
                    token.value.type_name(),
                    provenance(token).map_or_else(String::new, |note| format!(" · {note}"))
                );
                typescript_doc(token.description.as_deref(), Some(&note), 1, out);
                let _ = writeln!(
                    out,
                    "  readonly {}: {};",
                    typescript_property(token.path.last().map_or("", String::as_str)),
                    if token.value.is_typescript_number() {
                        "number"
                    } else {
                        "string"
                    }
                );
            }
        }
    }
}

fn typescript_doc(description: Option<&str>, note: Option<&str>, depth: usize, out: &mut String) {
    if description.is_none() && note.is_none() {
        return;
    }
    let pad = "  ".repeat(depth);
    let _ = writeln!(out, "{pad}/**");
    if let Some(description) = description {
        for line in wrap(description, COMMENT_WIDTH - pad.len() - 3) {
            let _ = writeln!(out, "{pad} * {line}");
        }
    }
    if let Some(note) = note {
        if description.is_some() {
            let _ = writeln!(out, "{pad} *");
        }
        for line in wrap(note, COMMENT_WIDTH - pad.len() - 3) {
            let _ = writeln!(out, "{pad} * {line}");
        }
    }
    let _ = writeln!(out, "{pad} */");
}

fn typescript_values(entries: &[Entry], depth: usize, out: &mut String) {
    let pad = "  ".repeat(depth);
    for entry in entries {
        match entry {
            Entry::Group(group) => {
                let _ = writeln!(
                    out,
                    "{pad}{}: {{",
                    typescript_property(group.path.last().map_or("", String::as_str))
                );
                typescript_values(&group.entries, depth + 1, out);
                let _ = writeln!(out, "{pad}}},");
            }
            Entry::Token(token) => {
                let rendered = token.value.css();
                let value = if token.value.is_typescript_number() {
                    rendered
                } else {
                    format!("'{}'", rendered.replace('\\', "\\\\").replace('\'', "\\'"))
                };
                let _ = writeln!(
                    out,
                    "{pad}{}: {value},",
                    typescript_property(token.path.last().map_or("", String::as_str))
                );
            }
        }
    }
}

