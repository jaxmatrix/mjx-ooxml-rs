/// Renders `crates/mjx-tokens/src/generated.rs`: the group structs, the `Tokens` struct, its
/// `const` default table, the two accessors the runtime resolver drives it through, and the index
/// that ties a token's three names together.
///
/// The output is not formatted here; [`super::run`] passes it through `rustfmt` the same way the
/// schema codegen does, so `cargo fmt --all --check` and this generator can never disagree about
/// the committed file.
pub(crate) fn rust(set: &TokenSet) -> String {
    let tokens = set.tokens();
    let mut out = String::new();
    let _ = writeln!(out, "//! {GENERATED_BY}");
    out.push_str("//! DO NOT EDIT. Edit the source and regenerate.\n//!\n");
    for line in wrap(&set.description, COMMENT_WIDTH - 4) {
        let _ = writeln!(out, "//! {line}");
    }

    let mut imports: BTreeSet<&'static str> =
        ["Derivation", "TokenError", "TokenIdentity", "TokenValue"]
            .into_iter()
            .collect();
    imports.insert("parse_token");
    for token in &tokens {
        for name in rust_imports(&token.value) {
            imports.insert(name);
        }
        // Only when something actually declares one, so a source with no colours in it emits a file
        // that still compiles rather than one with an unused import.
        if token.usage.is_some() {
            imports.insert("ColorUsage");
        }
        let Some(derivation) = &token.derivation else {
            continue;
        };
        imports.insert("DerivedFrom");
        let Derivation::Mix(nodes) = derivation else {
            continue;
        };
        imports.insert("MixNode");
        imports.insert("MixTerm");
        for node in nodes {
            if matches!(node.first, MixTerm::Literal(_))
                || matches!(node.second, MixTerm::Literal(_))
            {
                imports.insert("Color");
            }
            for percentage in [&node.first_percentage, &node.second_percentage] {
                match percentage {
                    None => {}
                    Some(MixPercentage::Fixed(_)) => {
                        imports.insert("MixPercentage");
                        imports.insert("Percentage");
                    }
                    Some(MixPercentage::Token(_)) => {
                        imports.insert("MixPercentage");
                    }
                }
            }
        }
    }
    let _ = writeln!(
        out,
        "\nuse crate::{{{}}};\n",
        imports.into_iter().collect::<Vec<_>>().join(", ")
    );

    let mut emitted: BTreeSet<&str> = BTreeSet::new();
    for group in set.groups() {
        if !emitted.insert(group.rust_type.as_str()) {
            continue;
        }
        rust_struct(
            &group.rust_type,
            group.description.as_deref(),
            &group.entries,
            &mut out,
        );
    }

    if !set.scheme_names.is_empty() {
        rust_scheme_enum(set, &mut out);
        let mut seen: BTreeSet<&str> = BTreeSet::new();
        for group in set.groups().into_iter().filter(|group| group.schemes) {
            if !seen.insert(group.rust_type.as_str()) {
                continue;
            }
            rust_scheme_accessor(set, group, &mut out);
        }
    }

    rust_struct(
        "Tokens",
        Some(
            "The whole design-token set: the values the client platform ships with, and the shape a \
             host's overrides are resolved into.",
        ),
        &set.entries,
        &mut out,
    );

    out.push_str(
        "
impl Tokens {
    /// The generated defaults — the bottom of the resolution order *explicit configuration →
    /// host-supplied overrides → generated defaults*.
    pub const DEFAULTS: Self = Self {
",
    );
    rust_default_members(&set.entries, 2, &mut out);
    out.push_str("    };\n");

    out.push_str(
        "
    /// The typed value of one token, by the CSS custom property that names it, or `None` when the
    /// platform defines no such token.
    #[must_use]
    pub fn custom_property(&self, custom_property: &str) -> Option<TokenValue> {
        Some(match custom_property {
",
    );
    for token in &tokens {
        let _ = writeln!(
            out,
            "            {:?} => TokenValue::{}(self.{}{}),",
            custom_property(&token.path),
            rust_token_value_variant(&token.value),
            rust_access(&token.path),
            if matches!(token.value, Value::FontStack(_)) {
                ".clone()"
            } else {
                ""
            }
        );
    }
    out.push_str("            _ => return None,\n        })\n    }\n");

    out.push_str(
        "
    /// Replaces one token's value, parsed from the CSS text a host declared it with.
    ///
    /// # Errors
    ///
    /// [`TokenError::UnknownCustomProperty`] when the platform defines no such token, and
    /// [`TokenError::MalformedValue`] when the text is not a value of that token's type.
    pub fn set_custom_property(
        &mut self,
        custom_property: &str,
        css_text: &str,
    ) -> Result<(), TokenError> {
        match custom_property {
",
    );
    for token in &tokens {
        let _ = writeln!(
            out,
            "            {:?} => self.{} = parse_token(custom_property, css_text)?,",
            custom_property(&token.path),
            rust_access(&token.path)
        );
    }
    out.push_str(
        "            _ => {
                return Err(TokenError::UnknownCustomProperty {
                    custom_property: custom_property.to_owned(),
                })
            }
        }
        Ok(())
    }
}

/// Every token the platform defines, in the order the source declares them, with the three names it
/// goes by — its path in `tokens.json`, its CSS custom property, and its path in `tokens.ts` — and
/// the contrast metadata every colour carries.
///
/// This is what makes the three artefacts comparable. A test that had to re-derive
/// `--color-ink-soft` from `color.inkSoft` itself could agree perfectly with a wrong rule.
///
/// `usage` and `background` are emitted as **data** rather than only as prose in each token's docs
/// (MJXOFF-166), because `xtask`'s generator is not the only writer of `tokens.json`: the canvas
/// harness's live token editor writes back to it and may not depend on `xtask`, so it has to be
/// able to call `mjx_tokens::check_usage` for itself.
pub const TOKENS: &[TokenIdentity] = &[
",
    );
    for token in &tokens {
        let _ = writeln!(
            out,
            "    TokenIdentity {{ path: {:?}, custom_property: {:?}, typescript_path: {:?}, \
             usage: {}, background: {} }},",
            dotted(&token.path),
            custom_property(&token.path),
            typescript_path(&token.path),
            match token.usage {
                None => "None".to_owned(),
                Some(usage) => format!("Some(ColorUsage::{})", usage_variant(usage)),
            },
            match &token.background {
                None => "None".to_owned(),
                Some(path) => format!("Some({path:?})"),
            }
        );
    }
    out.push_str("];\n");

    rust_derivations(set, &mut out);
    out
}

/// The derived tier, as the table `mjx_tokens::Tokens::rederive` walks.
///
/// Emitted in token order, which [`crate::codegen::tokens::model`] has already checked is a
/// topological order — so one forward pass is enough and the runtime needs no scheduler.
fn rust_derivations(set: &TokenSet, out: &mut String) {
    let derived: Vec<&Token> = set
        .tokens()
        .into_iter()
        .filter(|token| token.derivation.is_some())
        .collect();

    out.push_str(
        "
/// Every derived colour, and the `color-mix(in srgb, …)` expression it comes from.
///
/// The committed value of a derived token is what this expression evaluated to for the seeds and
/// knobs the source ships with. `Tokens::rederive` re-evaluates it for whichever seeds actually
/// won, which is the fourth step of the resolution order and the reason a host can re-theme the
/// whole platform by setting one custom property.
///
/// `ui/tokens/derivations.css` states the same expressions for the browser, so the chrome
/// re-derives through the cascade with no code at all;
/// `ui/tokens/chromium-agreement.mjs` asserts the two evaluators agree.
pub const DERIVATIONS: &[Derivation] = &[
",
    );
    for token in derived {
        let derivation = token
            .derivation
            .as_ref()
            .expect("filtered to the derived tokens");
        let _ = writeln!(
            out,
            "    // {}\n    Derivation {{ custom_property: {:?}, source: ",
            dotted(&token.path),
            custom_property(&token.path)
        );
        match derivation {
            Derivation::Alias(path) => {
                let _ = writeln!(
                    out,
                    "        DerivedFrom::Token({:?}),",
                    rust_reference(path)
                );
            }
            Derivation::Mix(nodes) => {
                out.push_str("        DerivedFrom::Mix(&[\n");
                for node in nodes {
                    let _ = writeln!(out, "            {},", rust_mix_node(set, node));
                }
                out.push_str("        ]),\n");
            }
        }
        out.push_str("    },\n");
    }
    out.push_str("];\n");
}

/// A dotted token path as the custom property the Rust table names it by — the token's **own**
/// property, never the scheme alias, for the reason `mjx_tokens::MixTerm::Token` documents.
fn rust_reference(path: &str) -> String {
    custom_property(&path.split('.').map(str::to_owned).collect::<Vec<_>>())
}

fn rust_mix_node(set: &TokenSet, node: &MixNode) -> String {
    format!(
        "MixNode {{ first: {}, first_percentage: {}, second: {}, second_percentage: {} }}",
        rust_mix_term(set, &node.first),
        rust_mix_percentage(set, &node.first_percentage),
        rust_mix_term(set, &node.second),
        rust_mix_percentage(set, &node.second_percentage),
    )
}

fn rust_mix_term(set: &TokenSet, term: &MixTerm) -> String {
    match term {
        MixTerm::Literal(colour) => format!("MixTerm::Literal({})", rust_colour(*colour)),
        MixTerm::Transparent => "MixTerm::Transparent".to_owned(),
        MixTerm::Nested(at) => format!("MixTerm::Nested({at})"),
        // The token's OWN property, never the scheme alias: this table is read by a renderer that
        // already knows which scheme it is painting. `derivations.css` is where the alias goes.
        MixTerm::Token(path) => {
            let _ = set;
            format!("MixTerm::Token({:?})", rust_reference(path))
        }
    }
}

fn rust_mix_percentage(set: &TokenSet, percentage: &Option<MixPercentage>) -> String {
    match percentage {
        None => "None".to_owned(),
        Some(MixPercentage::Fixed(value)) => format!(
            "Some(MixPercentage::Fixed(Percentage {{ value: {} }}))",
            rust_float(*value)
        ),
        Some(MixPercentage::Token(path)) => {
            let _ = set;
            format!("Some(MixPercentage::Token({:?}))", rust_reference(path))
        }
    }
}

